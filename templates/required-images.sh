#!/usr/bin/env bash
# List every container image the pipeline, the image builds and the test
# deployment need for the checked-out version, with the rule for picking a
# substitute when the company registry (Harbor) lacks that exact tag.
#
#   bash required-images.sh [repo]             # table, for asking for images
#   bash required-images.sh [repo] --yaml      # draft company/ci/images.yml
#
# The YAML draft has the upstream references as values. Replace each value with
# the registry path that exists inside the company, keep the comment, and add
# why when you picked a substitute. DIAGNOSE.md says how to check the result.
set -euo pipefail
repo=${1:-.}; [ "${1:-}" = --yaml ] && repo=.
fmt=table; for a in "$@"; do [ "$a" = --yaml ] && fmt=yaml; done
cd "$repo"

from() { # from DOCKERFILE N -> image of the Nth FROM line (1-based)
  grep -E '^FROM ' "$1" | sed -n "${2}p" | awk '{print $2}'
}
go_mod=$(awk '$1=="go"{print $2}' server/go.mod)
go_release=$(grep -hoE 'go-version: "~?[0-9.]+"' .github/workflows/release.yml 2>/dev/null | head -1 | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' || echo "$go_mod")
node=$(cat .nvmrc)
pg=$(awk '/^  postgres:/{f=1} f&&/repository:/{r=$2} f&&/tag:/{print r":"$2; exit}' deploy/helm/multica/values.yaml)
go_build=$(from Dockerfile 1); alpine_rt=$(from Dockerfile 2)
node_alpine=$(from Dockerfile.web 1)

# KEY | upstream reference | used by | substitute rule
rows=$(cat <<EOF
IMG_GO_BUILD|$go_build|Dockerfile build stage|Go >= $go_mod (server/go.mod), alpine variant; prefer the exact tag
IMG_ALPINE_RUNTIME|$alpine_rt|Dockerfile runtime stage|an Alpine release the apk mirror (or proxy) serves; the packages the Dockerfile installs must exist in it
IMG_NODE_ALPINE|$node_alpine|Dockerfile.web all stages|Node major ${node%%.*} (.nvmrc $node), alpine variant whose apk has the libssl3 version Dockerfile.web asks for
IMG_POSTGRES|$pg|go-test service, Helm chart|PostgreSQL major must match exactly (pg17), with pgvector
IMG_CI_BASE|ubuntu:24.04|CI image OS|a Debian or Ubuntu release the apt mirror (or proxy) serves, with git >= 2.40: Debian trixie, Ubuntu 24.04 or newer
IMG_GO_CI|golang:$go_mod-trixie|CI image (Go copied in), probe jobs|Go >= $go_mod; a Debian-based golang image (the probe runs its bash checks in it)
IMG_NODE_CI|node:$node-bookworm-slim|CI image (Node copied in)|Node major ${node%%.*}, glibc (Debian) variant
IMG_GO_RELEASE|golang:$go_release-bookworm|cli job|same Go as upstream's release workflow ($go_release); a newer patch is fine
IMG_HELM|alpine/helm:3.18.4|helm job, CI image|any Helm 3
IMG_YQ|mikefarah/yq:4.47.1|CI image|any yq 4
IMG_COMPOSE|docker/compose-bin:v2.39.4|CI image (docker compose plugin)|any Compose v2
IMG_DOCKER_CLI|docker:28.3.3-cli|CI image (docker CLI)|any recent Docker CLI
IMG_KANIKO|gcr.io/kaniko-project/executor:v1.23.2-debug|images job|any Kaniko, the -debug variant (it has a shell)
EOF
)

if [ "$fmt" = table ]; then
  printf '%-20s %-48s %s\n' KEY UPSTREAM "SUBSTITUTE RULE"
  while IFS='|' read -r k ref use rule; do printf '%-20s %-48s %s (%s)\n' "$k" "$ref" "$rule" "$use"; done <<<"$rows"
  exit 0
fi
echo "# Container images, for this version. Generated by required-images.sh,"
echo "# then each value replaced with the path inside the company registry."
echo "variables:"
while IFS='|' read -r k ref use rule; do
  printf '  # %s; substitute: %s\n  %s: "%s"\n' "$use" "$rule" "$k" "$ref"
  # the images job rewrites FROM <upstream> to the value above
  printf '  UPSTREAM_%s: "%s"\n' "$k" "$ref"
done <<<"$rows"
echo '  # Built by this project from templates/ci-tools.Dockerfile'
echo '  IMG_CI_TOOLS: "$CI_REGISTRY_IMAGE/ci-tools:1"'
