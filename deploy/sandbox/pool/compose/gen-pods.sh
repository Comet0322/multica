#!/bin/sh
# Prints a compose file with N sandbox pods, each built the way the Kubernetes
# Deployment builds one (pool/k8s/pool.yaml):
#
#   podN-net     holds the pod's network namespace and IP, like the Kubernetes
#                pause container: it never restarts, so the daemon and the
#                runner can restart without losing the network (and with it the
#                abstract unix socket they talk over)
#   podN-daemon  daemon container, uid 1001
#   podN-runner  agent container, uid 1000
#   shared       /work and /tmp (volumes owned by 1001:2000, setgid, from the
#                image), /dev/shm (one tmpfs volume both containers mount,
#                group-writable, as an emptyDir with medium Memory)
#
# Usage: gen-pods.sh [N] > pods.yaml     (IMAGE, NETWORK override the defaults)
set -eu
n="${1:-4}"
image="${IMAGE:-multica-sandbox-pool:0.7.0}"
network="${NETWORK:-multica-sandbox}"

cat <<YAML
# Generated by gen-pods.sh; do not edit.
x-pod-hardening: &hardening
  read_only: true
  cap_drop: [ALL]
  security_opt: ["no-new-privileges:true"]
  restart: always

networks:
  pods:
    name: ${network}

services:
YAML

i=1
while [ "$i" -le "$n" ]; do
	cat <<YAML
  pod${i}-net:
    <<: *hardening
    image: ${image}
    entrypoint: ["sleep", "infinity"]
    init: true
    stop_grace_period: 1s
    user: "1001:2000"
    networks: [pods]
    deploy: {resources: {limits: {cpus: "0.1", memory: 16M}}}
  pod${i}-daemon:
    <<: *hardening
    image: ${image}
    user: "1001:2000"
    network_mode: "service:pod${i}-net"
    depends_on: [pod${i}-net]
    environment: {POD_POLL_INTERVAL: 2s, POD_SHM_DIR: /dev/shm}
    volumes:
      - pod${i}-work:/work
      - pod${i}-tmp:/tmp
      - pod${i}-shm:/dev/shm
      - pod${i}-daemon-home:/home/daemon
    deploy: {resources: {limits: {cpus: "1", memory: 1G}}}
  pod${i}-runner:
    <<: *hardening
    image: ${image}
    user: "1000:2000"
    network_mode: "service:pod${i}-net"
    depends_on: [pod${i}-net]
    environment: {POD_ROLE: runner, POD_SHM_DIR: /dev/shm}
    volumes:
      - pod${i}-work:/work
      - pod${i}-tmp:/tmp
      - pod${i}-shm:/dev/shm
      - pod${i}-agent-home:/home/agent
    deploy: {resources: {limits: {cpus: "4", memory: 8G}}}
YAML
	i=$((i + 1))
done

echo "volumes:"
i=1
while [ "$i" -le "$n" ]; do
	cat <<YAML
  pod${i}-work: {}
  pod${i}-tmp: {}
  pod${i}-daemon-home: {}
  pod${i}-agent-home: {}
  pod${i}-shm:
    driver: local
    driver_opts: {type: tmpfs, device: tmpfs, o: "size=1g,uid=1001,gid=2000,mode=2770"}
YAML
	i=$((i + 1))
done
