#!/usr/bin/env bash
# Creates the PoC fixtures through the public API: two workspaces (A, B), an
# admin + member in A, an admin in B, and a PAT for each. Writes state.env.
set -euo pipefail
cd "$(dirname "$0")"
. ./lib.sh
OUT=${STATE_FILE:-state.env}

echo "# generated by bootstrap.sh" > "$OUT"
for u in admin_a member_a admin_b; do
  email="${u//_/-}@poc.test"
  tok=$(login "$email")
  [ "$tok" != "null" ] && [ -n "$tok" ] || { echo "login failed for $email" >&2; exit 1; }
  echo "JWT_${u}=$tok" >> "$OUT"
done
. "./$OUT"

ws_a=$(call "$JWT_admin_a" - POST /api/workspaces '{"name":"PoC A","slug":"poc-a"}' | jq -r .id)
ws_b=$(call "$JWT_admin_b" - POST /api/workspaces '{"name":"PoC B","slug":"poc-b"}' | jq -r .id)
echo "WS_A=$ws_a" >> "$OUT"; echo "WS_B=$ws_b" >> "$OUT"

for pair in "admin_a:$JWT_admin_a" "member_a:$JWT_member_a" "admin_b:$JWT_admin_b"; do
  name=${pair%%:*}; tok=${pair#*:}
  pat=$(call "$tok" - POST /api/tokens "{\"name\":\"poc-$name\"}" | jq -r '.token // empty')
  echo "PAT_${name}=$pat" >> "$OUT"
done
cat "$OUT" | sed -E 's/(=.{14}).*/\1.../'
