package runtimecontroller

import (
	"fmt"
	"regexp"
	"strings"

	corev1 "k8s.io/api/core/v1"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/runtime/schema"
)

// Sandbox is the agent-sandbox CRD: https://github.com/kubernetes-sigs/agent-sandbox
var sandboxGVR = schema.GroupVersionResource{Group: "agents.x-k8s.io", Version: "v1beta1", Resource: "sandboxes"}

const (
	LabelManagedBy   = "app.kubernetes.io/managed-by"
	ManagedByValue   = "multica-runtime-controller"
	LabelWorkspaceID = "multica.ai/workspace-id"
	LabelDaemonID    = "multica.ai/daemon-id"

	AnnotationTokenExpiresAt = "multica.ai/token-expires-at"

	ModeRunning   = "Running"
	ModeSuspended = "Suspended"

	tokenSecretKey = "token"
	llmSecretKey   = "key"
	tokenMountPath = "/var/run/multica"
	dataMountPath  = "/data"
	agentUID       = 10001
)

var dnsLabelUnsafe = regexp.MustCompile(`[^a-z0-9-]+`)

// ObjectName derives the Sandbox/Secret name for a daemon id. Daemon ids are
// generated by the platform (mr-<uuid>); anything else is sanitized.
func ObjectName(daemonID string) (string, error) {
	n := strings.Trim(dnsLabelUnsafe.ReplaceAllString(strings.ToLower(daemonID), "-"), "-")
	if n == "" || len(n) > 50 { // leave room for the -token / -llm suffixes
		return "", fmt.Errorf("daemon id %q cannot be mapped to a Kubernetes name (1-50 chars)", daemonID)
	}
	return n, nil
}

func tokenSecretName(name string) string { return name + "-token" }
func llmSecretName(name string) string   { return name + "-llm" }

// SandboxSpec is what the reconciler asks Kube to create.
type SandboxSpec struct {
	Name        string
	WorkspaceID string
	DaemonID    string
	// LLM is true when the Sandbox gets LLM credentials from its -llm Secret.
	LLM bool
}

func (c Config) labels(workspaceID, daemonID string) map[string]string {
	return map[string]string{
		LabelManagedBy:   ManagedByValue,
		LabelWorkspaceID: workspaceID,
		LabelDaemonID:    daemonID,
	}
}

// BuildSandbox renders the Sandbox object: a hardened pod running the managed
// daemon, a PVC for the workdir and agent home, the daemon token as a mounted
// file (so rotation reaches a running pod), and optional LLM env.
func BuildSandbox(c Config, s SandboxSpec) *unstructured.Unstructured {
	uid := int64(agentUID)
	yes, no := true, false
	grace := int64(c.DrainTimeout.Seconds()) + 30

	env := []corev1.EnvVar{
		{Name: "MULTICA_SERVER_URL", Value: c.PodServerURL},
		{Name: "MULTICA_DAEMON_ID", Value: s.DaemonID},
		{Name: "MULTICA_DAEMON_DEVICE_NAME", Value: "managed-" + s.Name},
		{Name: "MULTICA_WORKSPACES_ROOT", Value: c.WorkspacesRoot},
		{Name: "MULTICA_DAEMON_DRAIN_TIMEOUT", Value: c.DrainTimeout.String()},
		{Name: "HOME", Value: dataMountPath + "/home"},
		{Name: "TMPDIR", Value: dataMountPath + "/tmp"},
	}
	var envFrom []corev1.EnvFromSource
	if s.LLM {
		optional := false
		envFrom = append(envFrom, corev1.EnvFromSource{SecretRef: &corev1.SecretEnvSource{
			LocalObjectReference: corev1.LocalObjectReference{Name: llmSecretName(s.Name)},
			Optional:             &optional,
		}})
	}

	pod := map[string]any{
		"automountServiceAccountToken":  false,
		"enableServiceLinks":            false,
		"terminationGracePeriodSeconds": grace,
		"securityContext": map[string]any{
			"runAsNonRoot":   yes,
			"runAsUser":      uid,
			"runAsGroup":     uid,
			"fsGroup":        uid,
			"seccompProfile": map[string]any{"type": "RuntimeDefault"},
		},
		"containers": []any{map[string]any{
			"name":            "daemon",
			"image":           c.Image,
			"imagePullPolicy": c.ImagePullPolicy,
			"command": []any{"/app/multica", "daemon", "start", "--foreground", "--managed",
				"--token-file=" + tokenMountPath + "/" + tokenSecretKey},
			"env":     toAny(env),
			"envFrom": toAny(envFrom),
			"securityContext": map[string]any{
				"allowPrivilegeEscalation": no,
				"capabilities":             map[string]any{"drop": []any{"ALL"}},
			},
			"resources": map[string]any{
				"requests": map[string]any{"cpu": c.CPURequest, "memory": c.MemoryRequest},
				"limits":   map[string]any{"cpu": c.CPULimit, "memory": c.MemoryLimit},
			},
			"volumeMounts": []any{
				map[string]any{"name": "data", "mountPath": dataMountPath},
				map[string]any{"name": "daemon-token", "mountPath": tokenMountPath, "readOnly": yes},
			},
		}},
		"volumes": []any{map[string]any{
			"name": "daemon-token",
			"secret": map[string]any{
				"secretName":  tokenSecretName(s.Name),
				"defaultMode": int64(0o440),
			},
		}},
	}
	if c.RuntimeClassName != "" {
		pod["runtimeClassName"] = c.RuntimeClassName
	}
	if len(envFrom) == 0 {
		delete(pod["containers"].([]any)[0].(map[string]any), "envFrom")
	}

	labels := map[string]any{}
	for k, v := range c.labels(s.WorkspaceID, s.DaemonID) {
		labels[k] = v
	}
	return &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": sandboxGVR.GroupVersion().String(),
		"kind":       "Sandbox",
		"metadata":   map[string]any{"name": s.Name, "namespace": c.Namespace, "labels": labels},
		"spec": map[string]any{
			"operatingMode": ModeRunning,
			"podTemplate":   map[string]any{"metadata": map[string]any{"labels": labels}, "spec": pod},
			"volumeClaimTemplates": []any{map[string]any{
				"metadata": map[string]any{"name": "data"},
				"spec": map[string]any{
					"accessModes": []any{"ReadWriteOnce"},
					"resources":   map[string]any{"requests": map[string]any{"storage": c.PVCSize}},
				},
			}},
		},
	}}
}

// toAny converts typed k8s structs to the map form unstructured objects need.
func toAny[T any](in []T) []any {
	out := make([]any, 0, len(in))
	for _, v := range in {
		m, err := toMap(v)
		if err == nil {
			out = append(out, m)
		}
	}
	return out
}
